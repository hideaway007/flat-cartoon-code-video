"""Create a code-drawn cartoon project: python new_project.py <project_dir> [--ratio 16:9|2:1] [--update-libs]

<project>/production/        library (engine, toon, scenery, stage, poses, timing) + project files:
                             cast.py (characters), sets.py (backgrounds), segments/seg01.py, seg02.py (example shots)
<project>/assets/audio/      narration (+music) goes here
<project>/assets/bg/         generated by sets.py
<project>/out/               segments/ and the joined film
Project files are never overwritten. --update-libs refreshes the library files from the skill (after a skill fix).
"""
import shutil, sys, pathlib

SKILL = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--") and a not in ("16:9", "2:1")]
if len(args) != 1:
    sys.exit(__doc__)
P = pathlib.Path(args[0]).expanduser().resolve()
upd = "--update-libs" in sys.argv
for d in ("production/segments", "production/review", "production/stills", "assets/audio", "assets/bg", "out/segments"):
    (P / d).mkdir(parents=True, exist_ok=True)

LIBS = ["engine.py", "toon.py", "scenery.py", "stage.py", "poses.py", "timing.py", "overlays.py", "costumes.py",
        "crowds.py", "scenery_kits.py", "bust.py", "horse.py"]
for f in LIBS:
    if not (SKILL / "scripts" / f).exists():
        continue
    dst = P / "production" / f
    if dst.exists() and not upd:
        print("keep", dst.relative_to(P)); continue
    shutil.copy2(SKILL / "scripts" / f, dst); print("copy", dst.relative_to(P))
for f in ("cast.py", "sets.py", "segments/seg01.py", "segments/seg02.py"):
    dst = P / "production" / f
    if dst.exists():
        print("keep", dst.relative_to(P)); continue
    shutil.copy2(SKILL / "assets" / "templates" / f, dst); print("copy", dst.relative_to(P))
for src in sorted((SKILL / "assets" / "fonts").glob("*")) if (SKILL / "assets" / "fonts").exists() else []:
    dst = P / "assets" / "fonts" / src.name
    if not dst.exists() or upd:
        dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(src, dst)
fmt = P / "production" / "format.json"
if not fmt.exists():
    ratio = sys.argv[sys.argv.index("--ratio") + 1] if "--ratio" in sys.argv else "16:9"
    fmt.write_text('{"w": 1920, "h": %d}\n' % (1080 if ratio == "16:9" else 960)); print("format", ratio)
st = P / "production" / "STATE.md"
if not st.exists():
    st.write_text("# State\n\n## Done\n\n## Decisions (user)\n\n## Open problems\n\n## Next step\n")
print("project ready:", P)
